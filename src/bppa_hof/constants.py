"""物理常数、单位换算因子与方法特定系数。

所有数值均对照《生成焓相关》方法文档 (2.2 节) 定义，注释中标注对应出处。
"""

# --------------------------------------------------------------------------
# 能量单位换算
# --------------------------------------------------------------------------
# 文档: "kcal/mol 的转换因子为 627.51"
HARTREE_TO_KCAL_MOL = 627.51  # kcal/mol per Hartree
KCAL_TO_KJ = 4.184  # kJ per kcal
KJ_TO_KCAL = 1.0 / KCAL_TO_KJ

# --------------------------------------------------------------------------
# 热力学常数
# --------------------------------------------------------------------------
GAS_CONSTANT_R = 8.314462618  # J/(mol*K)
STANDARD_TEMPERATURE = 298.15  # K (文档: T 取值 298.15 K)
AVOGADRO = 6.02214076e23  # 1/mol

# 标准温度下的 RT, 单位 kcal/mol (晶格焓 RT 项使用)
RT_KCAL_MOL = GAS_CONSTANT_R * STANDARD_TEMPERATURE / 1000.0 * KJ_TO_KCAL

# --------------------------------------------------------------------------
# 体积单位换算: cm^3/mol -> nm^3 (每个式单位)
# 1 cm^3 = 1e21 nm^3; 除以阿伏伽德罗常数得到单个式单位体积
# --------------------------------------------------------------------------
CM3_MOL_TO_NM3 = 1e21 / AVOGADRO

# --------------------------------------------------------------------------
# 原子化能法: 单原子单点计算的固定焓校正
# 文档: "加和固定数值 0.00236048 Hartree"
# --------------------------------------------------------------------------
SINGLE_ATOM_ENTHALPY_CORRECTION_HARTREE = 0.00236048

# --------------------------------------------------------------------------
# VBT (基于体积理论) 晶格能系数 (文档 2.2.2 节)
# U_POT 单位 kJ/mol, V_m 单位 nm^3
# --------------------------------------------------------------------------
VBT_ALPHA = 117.3  # kJ/mol/nm  (阴阳离子比率相关, 本体系取值)
VBT_BETA = 51.9  # kJ/mol
VBT_A = 121.4  # kJ/mol  (U_POT > 5000 kJ/mol 分支)
VBT_UPOT_THRESHOLD_KJ = 5000.0  # kJ/mol, 两个 U_POT 表达式的分界

# --------------------------------------------------------------------------
# 离子结构形状 -> 晶格焓 RT 项中的 n 值
# 文档: "单原子取 3, 线性多原子取 5, 非线性多原子取 6"
# --------------------------------------------------------------------------
ION_SHAPE_N = {
    "monatomic": 3,
    "linear": 5,
    "nonlinear": 6,
}
